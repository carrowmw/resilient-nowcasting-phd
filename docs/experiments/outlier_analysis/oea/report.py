"""Assemble the comprehensive markdown report from the test result dicts."""
from __future__ import annotations

import datetime as _dt
import json

from . import config, plotting
from .loading import Dataset


def _fig(name: str, caption: str) -> str:
    return f"\n![{caption}]({plotting.rel_fig(name)})\n\n*{caption}*\n"


def _pct(x, digits=1):
    return "n/a" if x is None else f"{x*100:.{digits}f}%"


def _num(x, digits=3):
    return "n/a" if x is None else f"{x:.{digits}f}"


def build_report(ds: Dataset, results: dict, wandb_run: dict | None,
                 shared, run_meta: dict) -> str:
    md: list[str] = []
    A = md.append
    now = run_meta.get("generated_at", "")

    # ---------------------------------------------------------------- header
    A(f"# Outlier Event Analysis — ResilientIoT Spatiotemporal GNN\n")
    A(f"**Run:** `{ds.cfg.run_id}` (W&B `{ds.cfg.wandb_run_id}`)  |  "
      f"**Generated:** {now}  |  "
      f"**Analysis window:** {ds.dates[0]} → {ds.dates[-1]} "
      f"({len(ds.dates)} days, {ds.T} × 15-min steps)\n")
    A(f"**Network:** {len(ds.real_ids)} real nodes "
      f"({len(ds.observed_ids)} observed + {len(ds.holdout_ids)} inductive holdout), "
      f"{len(ds.sim_ids)} simulated (zero-shot) nodes.\n")
    A("> Data pulled live from Cloudflare R2 inference payloads and Weights & Biases; "
      "all figures and tables below are regenerated by `run_analysis.py`.\n")
    A("\n---\n")

    # -------------------------------------------------------- exec summary
    t1, t2, t3 = results["test1"], results["test2"], results["test3"]
    t4, t5, t6 = results["test4"], results["test5"], results["test6"]
    t7, t8 = results["test7"], results["test8"]

    A("## 1. Executive Summary\n")
    A(f"Across the {len(ds.dates)}-day window we flagged **{t1['total_flagged_steps']:,} "
      f"outlier (node, timestep) pairs** ({t1['mean_pct_flagged']:.2f}% of observed steps, "
      f"peak {t1['max_pct_flagged']:.1f}% of the network simultaneously), which merge into "
      f"**{t1['n_events']} distinct events** "
      f"({', '.join(f'{v} {k}' for k, v in t1['class_counts'].items())}).\n")

    bullets = [
        f"**Uncertainty is badly miscalibrated during outliers.** ZINB predictive variance "
        f"does widen (×{_num(t2['variance_ratio'],2)} vs baseline) and zero-inflation π "
        f"correctly falls (×{_num(t2['pi_ratio'],2)}), but not nearly enough: 99% interval "
        f"coverage collapses from {_pct(t2['coverage']['99']['baseline'])} at baseline to "
        f"**{_pct(t2['coverage']['99']['outlier'])}** during outliers. The model is "
        f"systematically over-confident exactly when it should hedge.",

        f"**Outlier information *does* reach zero-shot simulated nodes.** With outgoing edges "
        f"masked ({t3['sim_outgoing_edges']} outgoing vs {t3['sim_incoming_edges']:,} incoming "
        f"edges confirmed), simulated-node predictions still shift a median "
        f"{_num(t3['mu_shift_median_abs'],2)}σ during nearby real-node outliers "
        f"({_pct(t3['mu_shift_frac_gt_0p5z'])} of pairs shift >0.5σ) — propagation is real, "
        f"but it rides on the *prediction* pathway more than on visible attention "
        f"re-weighting (median attention shift {_num(t3['attention_shift_median'],2)}).",

        f"**The kriging head degrades under neighbour-outlier stress** "
        f"(RMSE {_num(t5['kriging_rmse_normal'],1)} → {_num(t5['kriging_rmse_exposed'],1)}, "
        f"×{_num(t5['kriging_degradation_ratio'],2)}), i.e. message passing propagates "
        f"neighbour anomalies into held-out reconstructions rather than smoothing them out.",

        f"**Scale-invariance holds.** At outlier steps the MSLE loss contribution of a "
        f"high-traffic vs a low-traffic sensor differs by only ×{_num(t7['msle_ratio_high_over_low'],2)}, "
        f"versus ×{_num(t7['se_ratio_high_over_low'],0)} for raw squared error — TRUE MSLE is "
        f"doing its job of equalising treatment across sensor scales.",
    ]
    for b in bullets:
        A(f"- {b}\n")
    A("\nBuild-up dynamics, tripwire behaviour and the two-extremes proxy are detailed in "
      "§4 and the per-test sections below.\n")
    A("\n---\n")

    # ------------------------------------------------------- catalogue table
    A("## 2. Outlier Catalogue (Top 20 events)\n")
    A("Ranked by severity (Σ peak z-score across affected nodes). "
      "Calendar column cross-references the deterministic UK-2026 calendar; football "
      "fixture / concert confirmation for this future window is a manual follow-up.\n\n")
    A("| # | Start | Dur (steps) | Class | # nodes | Peak % | Peak resid | Peak node | Calendar |\n")
    A("|---|-------|-------------|-------|---------|--------|-----------|-----------|----------|\n")
    for row in t1["catalogue"]:
        A(f"| {row['rank']} | {row['start'][:16]} | {row['duration_steps']} | "
          f"{row['classification']} | {row['n_affected']} | {row['peak_frac']*100:.0f}% | "
          f"{row['peak_residual']:.0f} | {row['peak_node_name'][:24]} | {row['calendar']} |\n")
    A("\n---\n")

    # ------------------------------------------------------- per-test detail
    A("## 3. Per-Test Results\n")

    # --- Test 1
    A("### Test 1 — Outlier Detection & Cataloguing\n")
    A(f"Per node we take the forecast residual `|gt − μ|`, standardise by the node's "
      f"residual σ, and flag steps beyond {config.RESIDUAL_SIGMA}σ. Flags are merged "
      f"temporally (gap tolerance {config.EVENT_GAP_TOLERANCE} step) into network events and "
      f"classified network-wide (≥{int(config.NETWORK_WIDE_FRAC*100)}% of nodes), cluster "
      f"(spatially contiguous) or isolated.\n")
    A(f"- Events: **{t1['n_events']}** — {t1['class_counts']}.\n")
    A("- Busiest nodes by outlier count: "
      + ", ".join(f"{b['name']} ({b['n_outliers']})" for b in t1['busiest_nodes']) + ".\n")
    A(_fig(t1["figures"][0], "Network-wide outlier activity across the analysis window."))
    A(_fig(t1["figures"][1], "Spatial distribution of outlier burden across real nodes."))

    # --- Test 2
    A("### Test 2 — ZINB Distribution Behaviour During Outliers\n")
    c = t2["coverage"]
    A("| Interval | Nominal | Baseline coverage | Outlier coverage |\n|---|---|---|---|\n")
    for lvl in ("50", "90", "99"):
        A(f"| {lvl}% | {lvl}% | {_pct(c[lvl]['baseline'])} | {_pct(c[lvl]['outlier'])} |\n")
    A(f"\n- ZINB variance `μ + μ²/θ` rises ×{_num(t2['variance_ratio'],2)} at outlier steps — "
      f"the head *does* react — but coverage still collapses, so the reaction is far too small.\n")
    A(f"- Zero-inflation π falls to ×{_num(t2['pi_ratio'],2)} of baseline during spikes: the "
      f"model correctly recognises these are **not** structural zeros.\n")
    A(_fig(t2["figures"][0], "Left: interval coverage (baseline vs outlier). "
                             "Right: mean ZINB variance and π."))

    # --- Test 3
    A("### Test 3 — Outlier Signal Propagation to Simulated (Zero-Shot) Nodes\n")
    A(f"Confirmed architecturally: simulated nodes have **{t3['sim_outgoing_edges']} outgoing** "
      f"and **{t3['sim_incoming_edges']:,} incoming** attention edges "
      f"({t3['sim_nodes_with_incoming']} sim nodes receive, "
      f"mean {_num(t3['mean_incoming_neighbours'],1)} real neighbours each).\n")
    A(f"- **Prediction response:** median |Δμ| of simulated nodes during nearby real-node "
      f"outliers = **{_num(t3['mu_shift_median_abs'],2)}σ**; "
      f"{_pct(t3['mu_shift_frac_gt_0p5z'])} of (source, sim) pairs move >0.5σ. Information "
      f"clearly propagates through the learned graph.\n")
    A(f"- **Attention response:** median relative attention shift toward the outlier source = "
      f"{_num(t3['attention_shift_median'],2)} ({_pct(t3['attention_shift_pos_frac'])} of pairs "
      f"increase). Attention does *not* consistently concentrate on the outlier — the response "
      f"is carried by the message content, not by visible re-weighting.\n")
    A(f"- **Latency:** median best-lag cross-correlation = {_num(t3['median_lag_steps'],1)} steps "
      f"(≈ {_num((t3['median_lag_steps'] or 0)*config.STEP_MINUTES,0)} min).\n")
    A(_fig(t3["figures"][0], "Left: distribution of attention re-weighting toward outlier "
                             "sources. Right: spatial decay of simulated-node response."))

    # --- Test 4
    A("### Test 4 — Outlier Build-Up Dynamics\n")
    s = t4["pre_event_slopes_per_hour"]
    A(f"Event-aligned composites over the {t4['n_events_used']} most severe events "
      f"(baseline-subtracted, {config.RAMP_UP_HOURS}h pre / post window).\n")
    A("| Signal | Pre-event slope (per hour) |\n|---|---|\n")
    for k, lab in [("mu", "μ (mean)"), ("theta", "θ (dispersion)"), ("pi", "π (zero-infl.)"),
                   ("impute_res", "imputation |resid|"), ("att_entropy", "attention entropy")]:
        A(f"| {lab} | {_num(s[k],4)} |\n")
    recov = t4["mu_recovery_hours"]
    recov_txt = (f"{recov:.1f} h" if recov is not None
                 else f">{config.RAMP_UP_HOURS}h (not reached within the post-event window)")
    A(f"\n- μ recovery time to <25% of peak: **{recov_txt}**. Positive pre-event slopes on μ, θ "
      f"and the imputation residual indicate the model registers a build-up *before* the "
      f"ground-truth spike; a slow μ recovery is the hysteresis signature.\n")
    A(_fig(t4["figures"][0], "Event-aligned build-up and recovery of internal signals."))

    # --- Test 5
    A("### Test 5 — Kriging Performance Stratified by Outlier Exposure\n")
    A("| Head | Normal RMSE | Neighbour-outlier RMSE | Degradation |\n|---|---|---|---|\n")
    A(f"| Kriging (held-out) | {_num(t5['kriging_rmse_normal'],2)} "
      f"| {_num(t5['kriging_rmse_exposed'],2)} | ×{_num(t5['kriging_degradation_ratio'],2)} |\n")
    A(f"| Imputation | {_num(t5['impute_rmse_normal'],2)} "
      f"| {_num(t5['impute_rmse_exposed'],2)} | ×{_num(t5['impute_degradation_ratio'],2)} |\n")
    A(f"\n- n(normal)={t5['n_normal']:,}, n(exposed)={t5['n_exposed']:,}. "
      f"Kriging error grows more than proportionally when an observed neighbour is anomalous — "
      f"message passing amplifies rather than damps neighbour outliers.\n")
    if wandb_run and wandb_run.get("summary"):
        sm = wandb_run["summary"]
        A(f"- W&B validation context: kriging RMSE {sm.get('val_kriging_rmse','?')}, "
          f"MAE {sm.get('val_kriging_mae','?')}, MSLE {sm.get('val_kriging_msle','?')}.\n")
    A(_fig(t5["figures"][0], "Holdout-node RMSE by neighbour outlier exposure, per head."))

    # --- Test 6
    A("### Test 6 — Tripwire Event Correlation with Outliers\n")
    A("| Type | Count | Median gt | % at night | % coincide outlier | Node Gini |\n"
      "|---|---|---|---|---|---|\n")
    for et, d in t6["by_type"].items():
        A(f"| {et} | {d['count']:,} | {_num(d['median_gt'],1)} | {_pct(d['frac_at_night'])} "
          f"| {_pct(d['frac_coincide_outlier'])} | {_num(d['node_gini'],2)} |\n")
    types_seen = list(t6["by_type"])
    only_pi = types_seen == ["PI_CLAMP"]
    pic = t6["by_type"].get("PI_CLAMP", {})
    A(f"\n- Total tripwires: {t6['total']:,}"
      + (" — **only `PI_CLAMP` fires**; no `MU_CLAMP` or `THETA_CLAMP` events occur at all."
         if only_pi else f" across types {types_seen}.") + "\n")
    if pic:
        A(f"- PI_CLAMP is **pervasive, not event-specific**: only {_pct(pic['frac_coincide_outlier'])} "
          f"of clamps coincide with a flagged outlier and only {_pct(pic['frac_at_night'])} occur at "
          f"night, at a median traffic level of {_num(pic['median_gt'],0)}. A low node-Gini "
          f"({_num(pic['node_gini'],2)}) shows the clamps are spread across the whole network rather "
          f"than concentrated at a few nodes. Interpretation: π is being driven to its lower bound "
          f"across ordinary daytime traffic (the model is near-certain there is no structural zero), "
          f"so PI_CLAMP is a *saturation* signal, not an outlier detector. The complete absence of "
          f"MU/THETA clamps suggests those bounds are never binding — the μ and θ ranges are "
          f"comfortably wide.\n")
    A(_fig(t6["figures"][0], "Tripwire counts by type and traffic level at each event."))

    # --- Test 7
    A("### Test 7 — Scale-Invariance Stress Test\n")
    hp, lp = t7["high_node"], t7["low_node"]
    if hp and lp:
        A(f"- High-traffic sensor: **{hp['name']}** (mean {_num(hp['mean_count'],1)}/interval, "
          f"{hp['n_outliers']} outliers). Low-traffic: **{lp['name']}** "
          f"(mean {_num(lp['mean_count'],1)}/interval, {lp['n_outliers']} outliers).\n")
        A(f"- MSLE contribution ratio (high/low) at outliers = "
          f"**×{_num(t7['msle_ratio_high_over_low'],2)}** vs raw-SE ratio "
          f"×{_num(t7['se_ratio_high_over_low'],0)}. MSLE nearly equalises the two scales; raw "
          f"MSE would be dominated by the city-centre sensor by orders of magnitude.\n")
    A(_fig(t7["figures"][0], "Left: MSLE vs raw-SE loss contribution, low vs high node. "
                             "Right: kriging MSLE at outliers vs node mean."))

    # --- Test 8
    A("### Test 8 — Two-Extremes Divergence as Outlier Indicator\n")
    mg = t8["median_gap_by_role"]
    if t8.get("degenerate_export"):
        A(f"> ⚠️ **Finding: the `two_extremes` export is degenerate in this run.** Across all "
          f"{t8['n_real_node_days_with_gap']:,} real node-days the fill-NaN and drop-NaN errors "
          f"are *identical* (nonzero-gap fraction = {_pct(t8['nonzero_gap_frac'],2)}), even though "
          f"nodes carry hundreds of missing steps each. The gap is therefore always 0 and cannot "
          f"be used as an outlier-severity proxy. This points to an export bug — the drop-NaN and "
          f"fill-NaN code paths are collapsing to the same computation — which should be fixed in "
          f"`export_paginated_payload.py` before the hypothesis can be tested.\n")
    A("\n| Role | Median gap (rmse_fill − rmse_drop) |\n|---|---|\n")
    for r in ("observed", "holdout", "simulated"):
        A(f"| {r} | {_num(mg.get(r),3)} |\n")
    A(f"\n- Spearman ρ(gap, #outlier steps/day) = **{_num(t8['spearman_gap_vs_outliers'],3)}** "
      f"over {t8['n_node_days']:,} node-days"
      + (" — undefined because the gap has zero variance (see finding above)."
         if t8.get("degenerate_export") else
         ". A positive correlation supports using the cheap two-extremes gap as an online "
         "outlier-severity proxy.") + "\n")
    A(_fig(t8["figures"][0], "Left: two-extremes gap by node role. Right: gap vs daily outlier count."))

    A("\n---\n")

    # ------------------------------------------------------ recommendations
    A("## 4. Recommendations\n")
    recs = [
        ("Fix outlier calibration first (highest impact).",
         f"99% coverage falls to {_pct(t2['coverage']['99']['outlier'])} during outliers. "
         "Add an explicit calibration objective (e.g. quantile/CRPS or a coverage-penalty term) "
         "and consider learning a per-step dispersion temperature so θ can inflate faster. "
         "Outlier-aware augmentation (inject synthetic spikes during training) would expose the "
         "ZINB head to the tail it currently under-models."),
        ("Add an event-detection / attention-temperature mechanism.",
         "Predictions propagate to simulated nodes without attention concentrating on the "
         "source. A learned attention temperature (sharpened during high-residual periods) or a "
         "dedicated event-detection head would let the graph route anomaly information "
         "deliberately instead of implicitly."),
        ("Make the kriging head outlier-robust.",
         f"Kriging degrades ×{_num(t5['kriging_degradation_ratio'],2)} under neighbour outliers. "
         "Robust aggregation (attention with outlier down-weighting, or a Huberised kriging "
         "loss) should reduce the amplification of neighbour anomalies into held-out nodes."),
        ("Fix the two-extremes export, then operationalise it.",
         "The drop-NaN and fill-NaN branches currently produce identical numbers "
         f"(gap ≡ 0 across all {t8['n_real_node_days_with_gap']:,} real node-days), so the metric "
         "is presently useless. Repair the export in `export_paginated_payload.py` so the two "
         "branches genuinely differ, then expose the gap as a live per-node anomaly signal."),
        ("Confirm real-world event attribution.",
         "Cross-reference the top catalogue timestamps against St James' Park fixtures, concerts "
         "and road-closure feeds for the analysis window to convert statistical outliers into "
         "labelled events."),
    ]
    for i, (title, body) in enumerate(recs, 1):
        A(f"{i}. **{title}** {body}\n")

    # ---------------------------------------------------------- appendix
    A("\n---\n")
    A("## Appendix — Method & Reproducibility\n")
    A(f"- Outlier rule: `|gt−μ| > {config.RESIDUAL_SIGMA}σ` per node (σ = residual std-dev). "
      f"Network-wide ≥ {int(config.NETWORK_WIDE_FRAC*100)}% of real nodes; spatial cluster "
      f"radius {config.SPATIAL_NEIGHBOUR_KM} km.\n")
    A("- ZINB coverage uses `n=θ, p=θ/(θ+μ)` with zero-inflation `F(k)=π+(1−π)F_nb(k)`.\n")
    A(f"- Reproduce: `python run_analysis.py --run-id {ds.cfg.run_id}`. Raw results in "
      f"`outputs/results.json`; figures in `outputs/figures/`.\n")
    if wandb_run:
        cfgc = wandb_run.get("config", {})
        loss = cfgc.get("loss", {})
        A(f"- Training config (W&B): loss weights {loss}, "
          f"seq_len {cfgc.get('data',{}).get('seq_len','?')}, "
          f"holdout frac {cfgc.get('data',{}).get('inductive_holdout_frac','?')}, "
          f"git `{run_meta.get('git_commit','?')[:10]}`.\n")

    return "".join(md)


def write_outputs(ds: Dataset, results: dict, wandb_run, shared, run_meta: dict) -> None:
    config.ensure_dirs()
    # JSON dump (strip figure-only noise is unnecessary; keep everything)
    payload = {"run_meta": run_meta, "results": results}
    (config.OUTPUT_DIR / "results.json").write_text(json.dumps(payload, indent=2, default=str))
    md = build_report(ds, results, wandb_run, shared, run_meta)
    config.REPORT_PATH.write_text(md)
